// Generates a SQL seed that sets document_chunks.embedding for the demo documents.
// Usage: node --env-file=.env.local scripts/generate-document-embeddings.mjs <output.sql>
// The API key is read from GEMINI_API_KEY and never printed.
import { readFileSync, writeFileSync } from "node:fs";
import { GoogleGenAI } from "@google/genai";

const EMBEDDING_MODEL = "gemini-embedding-2";
const DIMENSIONS = 768;

const output = process.argv[2];
if (!output) throw new Error("output path is required");
if (!process.env.GEMINI_API_KEY) throw new Error("GEMINI_API_KEY is not set");

const documents = JSON.parse(readFileSync(new URL("../supabase/seed-data/demo-documents.json", import.meta.url), "utf8"));
const ai = new GoogleGenAI({ apiKey: process.env.GEMINI_API_KEY });

function normalize(values) {
  const norm = Math.sqrt(values.reduce((sum, v) => sum + v * v, 0));
  return values.map((v) => v / norm);
}

const sqlString = (text) => `'${text.replaceAll("'", "''")}'`;
const statements = [];
for (const doc of documents) {
  const response = await ai.models.embedContent({
    model: EMBEDDING_MODEL,
    contents: doc.content,
    config: { outputDimensionality: DIMENSIONS, taskType: "RETRIEVAL_DOCUMENT" },
  });
  const values = response.embeddings?.[0]?.values;
  if (!values || values.length !== DIMENSIONS) throw new Error(`unexpected embedding for ${doc.title}`);
  const vector = `[${normalize(values).map((v) => v.toFixed(7)).join(",")}]`;
  statements.push(
    `update public.document_chunks c set embedding = '${vector}'::extensions.vector\n` +
      `from public.knowledge_documents d\n` +
      `where d.id = c.document_id and c.chunk_index = 0 and d.title = ${sqlString(doc.title)};`,
  );
  console.log(`embedded: ${doc.title}`);
}

writeFileSync(
  output,
  `-- DEMO document embeddings (${EMBEDDING_MODEL}, ${DIMENSIONS} dims, L2-normalized). Generated by scripts/generate-document-embeddings.mjs\n` +
    statements.join("\n\n") +
    "\n",
);
console.log(`wrote ${statements.length} statements`);
